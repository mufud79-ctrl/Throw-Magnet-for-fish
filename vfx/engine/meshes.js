// VFX mesh shapes shared by the viewer (three.js BufferGeometry) and the exporter (OBJ for Roblox).
// All shapes are unit-sized (fit a 1x1x1 box) so Size in studs = scale, like a Roblox SpecialMesh/MeshPart.
//   sphere            UV: u around, v pole to pole
//   band {arc, inner, cone, twist}   flat curved slash band in the XZ plane (u along the arc, v outer -> inner)
//   torus {tube, arc}  ring in the XZ plane (u around, v around the tube)
//   cylinder {cap}    open tube along Y (u around, v along)
//   cone              open cone along Y, apex at +Y
//   spiral {turns, width}  helical ribbon around Y (u along the helix, v across)
(function (G) {
  'use strict';
  const TAU = Math.PI * 2;
  function grid(nu, nv, fn) { // fn(u, v) -> [x, y, z]; returns indexed geometry with smooth normals
    const P = [], UV = [], I = [];
    for (let j = 0; j <= nv; j++) for (let i = 0; i <= nu; i++) { const u = i / nu, v = j / nv; P.push(fn(u, v)); UV.push([u, 1 - v]); }
    for (let j = 0; j < nv; j++) for (let i = 0; i < nu; i++) {
      const a = j * (nu + 1) + i, b = a + 1, c = a + nu + 1, d = c + 1;
      I.push(a, c, b, b, c, d);
    }
    const N = P.map(() => [0, 0, 0]);
    for (let k = 0; k < I.length; k += 3) {
      const [a, b, c] = [P[I[k]], P[I[k + 1]], P[I[k + 2]]];
      const e1 = [b[0] - a[0], b[1] - a[1], b[2] - a[2]], e2 = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
      const n = [e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0]];
      for (const idx of [I[k], I[k + 1], I[k + 2]]) { N[idx][0] += n[0]; N[idx][1] += n[1]; N[idx][2] += n[2]; }
    }
    for (const n of N) { const l = Math.hypot(...n) || 1; n[0] /= l; n[1] /= l; n[2] /= l; }
    return { P, N, UV, I };
  }
  const SHAPES = {
    sphere: () => grid(48, 32, (u, v) => { const a = u * TAU, b = v * Math.PI; return [Math.cos(a) * Math.sin(b) * 0.5, Math.cos(b) * 0.5, Math.sin(a) * Math.sin(b) * 0.5]; }),
    band: (o = {}) => {
      const arc = (o.arc || 270) * Math.PI / 180, inner = o.inner === undefined ? 0.55 : o.inner, cone = o.cone || 0, twist = o.twist || 0;
      return grid(64, 6, (u, v) => {
        const a = -arc / 2 + u * arc, r = 0.5 * (1 - v * (1 - inner)), y = v * cone * 0.5 + Math.sin(u * Math.PI) * twist * 0.5 * (1 - v);
        return [Math.cos(a) * r, y, Math.sin(a) * r];
      });
    },
    torus: (o = {}) => {
      const tube = o.tube || 0.08, arc = (o.arc || 360) * Math.PI / 180, R = 0.5 - tube;
      return grid(72, 12, (u, v) => { const a = u * arc, b = v * TAU, r = R + Math.cos(b) * tube; return [Math.cos(a) * r, Math.sin(b) * tube, Math.sin(a) * r]; });
    },
    cylinder: () => grid(48, 8, (u, v) => { const a = u * TAU; return [Math.cos(a) * 0.5, 0.5 - v, Math.sin(a) * 0.5]; }),
    cone: () => grid(48, 8, (u, v) => { const a = u * TAU, r = 0.5 * v; return [Math.cos(a) * r, 0.5 - v, Math.sin(a) * r]; }),
    spiral: (o = {}) => {
      const turns = o.turns || 3, w = o.width || 0.18;
      return grid(160, 4, (u, v) => { const a = u * turns * TAU, y = 0.5 - u, r = 0.5 - (v - 0.5) * w * 0; return [Math.cos(a) * 0.5, y + (v - 0.5) * w, Math.sin(a) * 0.5 * (r / 0.5)]; });
    },
  };
  function build(shape, args) {
    if (!SHAPES[shape]) throw new Error('Unknown mesh shape ' + shape);
    return SHAPES[shape](args || {});
  }
  const key = (shape, args) => shape + (args && Object.keys(args).length ? '_' + Object.entries(args).map(([k, v]) => k + v).join('_').replace(/[^\w]/g, '') : '');
  function toOBJ(g, name) {
    const L = [`# ${name} (unit size; generated by vfx/engine/meshes.js)`, `o ${name}`];
    for (const p of g.P) L.push(`v ${p[0].toFixed(5)} ${p[1].toFixed(5)} ${p[2].toFixed(5)}`);
    for (const t of g.UV) L.push(`vt ${t[0].toFixed(5)} ${t[1].toFixed(5)}`);
    for (const n of g.N) L.push(`vn ${n[0].toFixed(5)} ${n[1].toFixed(5)} ${n[2].toFixed(5)}`);
    for (let k = 0; k < g.I.length; k += 3) { const f = [g.I[k] + 1, g.I[k + 1] + 1, g.I[k + 2] + 1]; L.push(`f ${f.map((i) => `${i}/${i}/${i}`).join(' ')}`); }
    return L.join('\n') + '\n';
  }
  G.VFXMeshes = { build, key, toOBJ, SHAPES };
})(typeof window !== 'undefined' ? window : globalThis);
