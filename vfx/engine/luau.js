// Spec -> Roblox Luau ModuleScript. Output is self-contained: builds the emitter parts,
// schedules :Emit() / Rate windows, animates lights, and (client only) impact frames + camera shake.
(function (G) {
  'use strict';
  const RANGE = new Set(['Lifetime', 'Speed', 'Rotation', 'RotSpeed', 'FlipbookFramerate']);
  const NUMSEQ = new Set(['Size', 'Transparency', 'Squash']);
  const ENUMS = {
    Orientation: 'ParticleOrientation', EmissionDirection: 'NormalId', Shape: 'ParticleEmitterShape',
    ShapeStyle: 'ParticleEmitterShapeStyle', ShapeInOut: 'ParticleEmitterShapeInOut',
    FlipbookLayout: 'ParticleFlipbookLayout', FlipbookMode: 'ParticleFlipbookMode',
  };
  const n = (x) => (Math.round(x * 1000) / 1000).toString();
  const v3 = (a) => `Vector3.new(${a.map(n).join(', ')})`;

  function val(k, v) {
    if (k === 'Texture') return `TEXTURES.${v}`;
    if (k === 'Color') return typeof v === 'string' ? `ColorSequence.new(Color3.fromHex("${v}"))` : `CS({ ${v.map((p) => `{${n(p[0])}, "${p[1]}"}`).join(', ')} })`;
    if (NUMSEQ.has(k)) return typeof v === 'number' ? `NumberSequence.new(${n(v)})` : `NS({ ${v.map((p) => `{${p.map(n).join(', ')}}`).join(', ')} })`;
    if (RANGE.has(k)) return typeof v === 'number' ? `NumberRange.new(${n(v)})` : `NumberRange.new(${n(v[0])}, ${n(v[1])})`;
    if (k === 'SpreadAngle') return `Vector2.new(${n(v[0])}, ${n(v[1])})`;
    if (k === 'Acceleration') return v3(v);
    if (ENUMS[k]) return `Enum.${ENUMS[k]}.${v}`;
    if (typeof v === 'boolean') return v ? 'true' : 'false';
    return n(v);
  }

  function toLuau(fx) {
    const tex = [...new Set(fx.layers.map((l) => (l.mesh ? l.texture : l.props.Texture)).filter(Boolean))];
    const L = [];
    L.push(`-- ${fx.name} v${fx.version}: anime-style VFX`);
    L.push(`-- Hero elements are 4 stacked emitters (_glow/_rim/_mid/_core) on the same part with identical motion;`);
    L.push(`-- each uses a white flipbook and gets its colour from Color, so you can recolour the effect without new textures.`);
    L.push(`-- Generated by vfx/build.mjs from vfx/effects/*.js. Change the spec and rebuild; don't hand-edit.`);
    L.push(`-- 1) Upload every PNG in textures/ (Asset Manager > Bulk Import) and paste the ids below.`);
    L.push(`-- 2) Put this ModuleScript in ReplicatedStorage. On each client: require(it).Play(CFrame.new(pos)).`);
    L.push(`--    (Fire a RemoteEvent with FireAllClients from the server; impact frames + shake only run on clients.)`);
    L.push('');
    L.push('local RunService = game:GetService("RunService")');
    L.push('local Lighting = game:GetService("Lighting")');
    L.push('');
    L.push('local TEXTURES = {');
    for (const t of tex) L.push(`\t${t} = "rbxassetid://0", -- textures/${t}.png`);
    L.push('}');
    L.push('');
    L.push('local function NS(k) local t = {} for i, p in k do t[i] = NumberSequenceKeypoint.new(p[1], p[2], p[3] or 0) end return NumberSequence.new(t) end');
    L.push('local function CS(k) local t = {} for i, p in k do t[i] = ColorSequenceKeypoint.new(p[1], Color3.fromHex(p[2])) end return ColorSequence.new(t) end');
    L.push('');
    L.push('local LAYERS = {');
    for (const ly of fx.layers) {
      if (ly.mesh) continue;
      L.push('\t{');
      L.push(`\t\tname = "${ly.name}", -- ${ly.role}: ${ly.ref || ''}`);
      L.push(`\t\toffset = ${v3(ly.position || [0, 0, 0])},`);
      L.push(`\t\trotation = ${v3(ly.rotation || [0, 0, 0])}, -- degrees, CFrame.Angles order`);
      L.push(`\t\tpartSize = ${ly.part ? v3(ly.part.Size) : 'nil'},`);
      L.push(`\t\temits = { ${(ly.emits || []).map((e) => `{${n(e[0])}, ${e[1]}}`).join(', ')} },`);
      L.push(`\t\trate = { ${(ly.rate || []).map((r) => `{${r.map(n).join(', ')}}`).join(', ')} },`);
      L.push('\t\tprops = {');
      for (const [k, v] of Object.entries(ly.props)) L.push(`\t\t\t${k} = ${val(k, v)},`);
      L.push('\t\t},');
      L.push('\t},');
    }
    L.push('}');
    L.push('');
    L.push('local LIGHTS = {');
    for (const li of fx.lights || []) L.push(`\t{ offset = ${v3(li.position)}, color = Color3.fromHex("${li.Color}"), range = ${n(li.Range)}, keys = { ${li.Brightness.map((k) => `{${n(k[0])}, ${n(k[1])}}`).join(', ')} } },`);
    L.push('}');
    L.push('');
    L.push('-- Impact frames: ColorCorrection + Highlight on nearby characters + optional black void sphere');
    L.push('local FRAMES = {');
    for (const f of fx.impactFrames || []) {
      const hl = f.Highlight ? `Color3.fromHex("${f.Highlight.FillColor}")` : 'nil';
      L.push(`\t{ t = ${n(f.t)}, dur = ${n(f.dur)}, brightness = ${n(f.Brightness || 0)}, contrast = ${n(f.Contrast || 0)}, saturation = ${n(f.Saturation || 0)}, tint = Color3.fromHex("${f.TintColor || '#ffffff'}"), void = ${f.Void ? `Color3.fromHex("${f.Void}")` : 'nil'}, highlight = ${hl} },`);
    }
    L.push('}');
    const meshes = fx.layers.filter((l) => l.mesh);
    const mkeys = [...new Set(meshes.map((m) => G.VFXMeshes.key(m.mesh, m.meshArgs)))];
    const kv = (keys, fn) => (Array.isArray(keys) && Array.isArray(keys[0]) ? `{ ${keys.map((k) => `{${n(k[0])}, ${fn(k[1])}}`).join(', ')} }` : `{ {0, ${fn(keys === undefined ? 0 : keys)}}, {1, ${fn(keys === undefined ? 0 : keys)}} }`);
    const v3s = (v) => (Array.isArray(v) ? v3(v) : v3([v, v, v]));
    L.push('-- Meshes: upload every OBJ in out/meshes/ (Asset Manager > Meshes) and paste the ids below.');
    L.push('local MESHIDS = {');
    for (const k of mkeys) L.push(`\t["${k}"] = "rbxassetid://0", -- out/meshes/${k}.obj`);
    L.push('}');
    L.push('local MESHES = {');
    for (const m of meshes) {
      const col = typeof m.color === 'string' || m.color === undefined ? m.color || '#ffffff' : m.color[0][1];
      L.push(`\t{ name = "${m.name}", mesh = "${G.VFXMeshes.key(m.mesh, m.meshArgs)}", texture = TEXTURES.${m.texture}, material = "${m.material || 'ForceField'}", color = Color3.fromHex("${col}"),`);
      L.push(`\t\toffset = ${v3(m.position || [0, 0, 0])}, rotation = ${v3(m.rotation || [0, 0, 0])}, spinAxis = ${v3(m.spinAxis || [0, 1, 0])}, spin = ${typeof m.spin === 'number' ? n(m.spin) : 0}, velocity = ${v3(m.velocity || [0, 0, 0])},`);
      L.push(`\t\tspawns = { ${(m.spawns || [0]).map(n).join(', ')} }, life = ${n(m.life)}, size = ${kv(m.size, v3s)}, transparency = ${kv(m.transparency, n)} },`);
    }
    L.push('}');
    L.push(`local GRADE = { ${(fx.grade || []).map((g) => `{ t = ${n(g[0])}, b = ${n(g[1])}, c = ${n(g[2])}, s = ${n(g[3])}, tint = Color3.fromHex("${g[4] || '#ffffff'}") }`).join(', ')} }`);
    L.push(`local SHAKES = { ${(fx.shakes || []).map((s) => `{ t = ${n(s.t)}, dur = ${n(s.dur)}, amp = ${n(s.amp)}, freq = ${n(s.freq)} }`).join(', ')} }`);
    L.push('');
    L.push(RUNTIME.replace('__DURATION__', n(fx.duration)).replace(/__NAME__/g, fx.name));
    return L.join('\n');
  }

  const RUNTIME = `local function track(keys, t)
	if t <= keys[1][1] then return keys[1][2] end
	for i = 2, #keys do
		local a, b = keys[i - 1], keys[i]
		if t <= b[1] then return a[2] + (b[2] - a[2]) * (t - a[1]) / math.max(b[1] - a[1], 1e-6) end
	end
	return keys[#keys][2]
end

local function keyAt(keys, k)
	if k <= keys[1][1] then return keys[1][2] end
	for i = 2, #keys do
		local a, b = keys[i - 1], keys[i]
		if k <= b[1] then return a[2] + (b[2] - a[2]) * ((k - a[1]) / math.max(b[1] - a[1], 1e-6)) end
	end
	return keys[#keys][2]
end

local function playMesh(m, origin, folder)
	for _, s0 in m.spawns do
		task.delay(s0, function()
			local p = Instance.new("Part")
			p.Name = m.name
			p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch, p.CastShadow = true, false, false, false, false
			p.Size = Vector3.new(0.05, 0.05, 0.05)
			p.Color = m.color
			p.Material = m.material == "Ink" and Enum.Material.SmoothPlastic or (m.material == "Neon" and Enum.Material.Neon or Enum.Material.ForceField)
			local sm = Instance.new("SpecialMesh")
			sm.MeshType = Enum.MeshType.FileMesh
			sm.MeshId = MESHIDS[m.mesh]
			sm.TextureId = m.texture
			sm.VertexColor = Vector3.new(m.color.R, m.color.G, m.color.B)
			sm.Parent = p
			local r = m.rotation * math.pi / 180
			local rot = CFrame.Angles(r.X, r.Y, r.Z)
			p.Parent = folder
			local t0 = os.clock()
			local conn
			conn = RunService.Heartbeat:Connect(function()
				local age = os.clock() - t0
				local k = age / m.life
				if k >= 1 or not p.Parent then conn:Disconnect(); p:Destroy(); return end
				sm.Scale = keyAt(m.size, k)
				p.Transparency = keyAt(m.transparency, k)
				p.CFrame = origin * CFrame.new(m.offset + m.velocity * age) * rot * CFrame.fromAxisAngle(m.spinAxis.Unit, math.rad(m.spin * age))
			end)
		end)
	end
end

local M = {}
M.Duration = __DURATION__

function M.Play(origin: CFrame, parent: Instance?)
	local folder = Instance.new("Folder")
	folder.Name = "__NAME__"
	folder.Parent = parent or workspace

	local function holder(name, cf, size)
		local p = Instance.new("Part")
		p.Name = name
		p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch, p.CastShadow = true, false, false, false, false
		p.Transparency = 1
		p.Size = size or Vector3.new(0.05, 0.05, 0.05) -- tiny part = point emitter
		p.CFrame = cf
		p.Parent = folder
		return p
	end

	for _, L in LAYERS do
		local r = L.rotation * math.pi / 180
		local part = holder(L.name, origin * CFrame.new(L.offset) * CFrame.Angles(r.X, r.Y, r.Z), L.partSize)
		local e = Instance.new("ParticleEmitter")
		e.Enabled = false
		e.Rate = 0
		for k, v in L.props do e[k] = v end
		e.Parent = part
		for _, em in L.emits do task.delay(em[1], function() e:Emit(em[2]) end) end
		for _, w in L.rate do
			task.delay(w[1], function() e.Rate = w[3]; e.Enabled = true end)
			task.delay(w[2], function() e.Enabled = false end)
		end
	end

	for _, m in MESHES do playMesh(m, origin, folder) end

	local lights = {}
	for i, li in LIGHTS do
		local p = holder("Light" .. i, origin * CFrame.new(li.offset))
		local pl = Instance.new("PointLight")
		pl.Color, pl.Range, pl.Brightness, pl.Shadows = li.color, li.range, 0, false
		pl.Parent = p
		lights[i] = { light = pl, keys = li.keys }
	end

	local isClient = RunService:IsClient()
	local cc, void, highlights
	if isClient then
		cc = Instance.new("ColorCorrectionEffect")
		cc.Enabled = false
		cc.Parent = Lighting
		void = Instance.new("Part")
		void.Anchored, void.CanCollide, void.CanQuery, void.CanTouch, void.CastShadow = true, false, false, false, false
		void.Size = Vector3.new(1, 1, 1)
		void.Material = Enum.Material.SmoothPlastic
		void.Transparency = 1
		void.CFrame = origin
		local mesh = Instance.new("SpecialMesh")
		mesh.MeshType = Enum.MeshType.Sphere
		mesh.Scale = Vector3.new(-900, -900, -900) -- negative scale renders the inside: a void backdrop
		mesh.Parent = void
		void.Parent = folder
		highlights = {}
		for _, m in workspace:GetDescendants() do
			if m:IsA("Humanoid") and m.Parent and m.Parent:IsA("Model") then
				local root = m.Parent.PrimaryPart
				if root and (root.Position - origin.Position).Magnitude < 80 then
					local h = Instance.new("Highlight")
					h.Enabled, h.FillTransparency, h.OutlineTransparency = false, 0, 1
					h.DepthMode = Enum.HighlightDepthMode.Occluded
					h.Adornee = m.Parent
					h.Parent = folder
					table.insert(highlights, h)
				end
			end
		end
	end

	local t0 = os.clock()
	local shakeName = "__NAME__Shake" .. tostring(t0)
	local conn
	conn = RunService.Heartbeat:Connect(function()
		local t = os.clock() - t0
		for _, l in lights do l.light.Brightness = math.max(0, track(l.keys, t)) end
		if isClient then
			local active
			for _, f in FRAMES do if t >= f.t and t < f.t + f.dur then active = f end end
			local g
			for i = 2, #GRADE do
				if t <= GRADE[i].t and t >= GRADE[i - 1].t then
					local a, b = GRADE[i - 1], GRADE[i]
					local e = (t - a.t) / math.max(b.t - a.t, 1e-6)
					g = { b = a.b + (b.b - a.b) * e, c = a.c + (b.c - a.c) * e, s = a.s + (b.s - a.s) * e, tint = a.tint:Lerp(b.tint, e) }
				end
			end
			if not active and g then active = { brightness = g.b, contrast = g.c, saturation = g.s, tint = g.tint } end
			cc.Enabled = active ~= nil
			void.Transparency = (active and active.void) and 0 or 1
			if active then
				cc.Brightness, cc.Contrast, cc.Saturation, cc.TintColor = active.brightness, active.contrast, active.saturation, active.tint
				if active.void then void.Color = active.void end
			end
			for _, h in highlights do
				h.Enabled = active ~= nil and active.highlight ~= nil
				if h.Enabled then h.FillColor = active.highlight end
			end
		end
		if t > M.Duration then conn:Disconnect() end
	end)

	if isClient then
		local cam = workspace.CurrentCamera
		RunService:BindToRenderStep(shakeName, Enum.RenderPriority.Camera.Value + 1, function()
			local t = os.clock() - t0
			for _, s in SHAKES do
				if t >= s.t and t < s.t + s.dur then
					local k = (t - s.t) / s.dur
					local amp, w = s.amp * (1 - k) ^ 2, (t - s.t) * s.freq
					cam.CFrame = cam.CFrame * CFrame.new(amp * math.sin(w * 6.1 + 1.3), amp * 0.8 * math.sin(w * 7.3 + 4.1), amp * 0.5 * math.sin(w * 5.2 + 2.2))
				end
			end
		end)
	end

	task.delay(M.Duration + 0.25, function()
		if isClient then
			RunService:UnbindFromRenderStep(shakeName)
			cc:Destroy()
		end
		folder:Destroy()
	end)
	return folder
end

return M`;

  G.VFXLuau = { toLuau };
})(typeof window !== 'undefined' ? window : globalThis);
