"""Export effect JSON specs to Roblox ModuleScripts and build the asset table + upload manifest.

    python3 export_luau.py [--effects ../lab/effects] [--out ../templates/ReplicatedStorage/AnimeVFX]

Writes
  <out>/Effects/<name>.lua   one ModuleScript per effect (returns the spec table the runtime plays)
  <out>/Assets.lua           texture + mesh id table. Paste uploaded ids; until then textures fall back to a
                             built-in sparkle so effects still play in Studio, and meshes are invisible
  ../assets/upload_manifest.json   exactly which PNG / FBX files the effects use (upload these, nothing else)
"""
import os
import re
import json
import glob
import argparse

HERE = os.path.dirname(os.path.abspath(__file__))
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def lua(v, ind=0):
    pad = "\t" * ind
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        if isinstance(v, float):
            s = f"{v:.4f}".rstrip("0").rstrip(".")
            return s if s not in ("", "-0") else "0"
        return str(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        flat = all(not isinstance(x, (list, dict)) for x in v)
        if flat or len(v) <= 4 and all(not isinstance(x, dict) for x in v):
            return "{ " + ", ".join(lua(x, ind) for x in v) + " }"
        return "{\n" + "".join(f"{pad}\t{lua(x, ind + 1)},\n" for x in v) + pad + "}"
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            if x is None:
                continue
            key = k if IDENT.match(k) else f"[{json.dumps(k)}]"
            items.append(f"{pad}\t{key} = {lua(x, ind + 1)},\n")
        return "{\n" + "".join(items) + pad + "}"
    raise TypeError(type(v))


def used_assets(spec):
    tex, meshes, models = set(), set(), set()
    for L in spec.get("layers", []):
        if L["type"] == "emitter":
            tex.add(L["props"]["Texture"])
        elif L["type"] in ("beam", "trail"):
            tex.update(L.get("textures") or [L["texture"]])
        elif L["type"] in ("rig", "attach"):
            models.add(L["model"])
        elif L["type"] == "vbeam":
            pls = L.get("planes") or []
            for pl in (pls if isinstance(pls, list) else [pls]):
                tex.update(pl.get("textures") or [pl["texture"]])
        elif L["type"] == "shell":
            meshes.add(L["mesh"])
            if L.get("texture"):
                tex.add(L["texture"])
    return tex, meshes, models


ASSETS_TEMPLATE = '''--!nonstrict
-- Asset ids for AnimeVFX. Upload the files listed (assets/upload_manifest.json) with the Asset Manager's bulk
-- import or the Creator Dashboard, then paste each id below. Generated by scripts/export_luau.py; keep ids when
-- regenerating by copying this table back in.
local FALLBACK_TEXTURE = "rbxasset://textures/particles/sparkles_main.dds" -- built-in, so effects play before upload

local TEXTURES = {{
{textures}}}

-- SpecialMesh.MeshId per kit mesh. The kit meshes are built to fit a 2-stud box; if an upload comes in at a
-- different size, set MESH_SCALE[name] so Scale 1 = that 2-stud box.
local MESHES = {{
{meshes}}}

local MESH_SCALE = {{}}

local Assets = {{}}

function Assets.texture(name)
	local id = TEXTURES[name]
	if id and id ~= "rbxassetid://0" then
		return id
	end
	return FALLBACK_TEXTURE
end

function Assets.mesh(name)
	local id = MESHES[name]
	return (id and id ~= "rbxassetid://0") and id or ""
end

function Assets.meshScale(name)
	return MESH_SCALE[name] or 1
end

Assets.TEXTURES = TEXTURES
Assets.MESHES = MESHES
return Assets
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--effects", default=os.path.join(HERE, "..", "lab", "effects"))
    ap.add_argument("--out", default=os.path.join(HERE, "..", "templates", "ReplicatedStorage", "AnimeVFX"))
    a = ap.parse_args()
    eff_dir = os.path.join(a.out, "Effects")
    os.makedirs(eff_dir, exist_ok=True)
    for f in glob.glob(os.path.join(eff_dir, "*.lua")):
        os.remove(f)
    all_tex, all_mesh, all_models = set(), set(), set()
    index = []
    for f in sorted(glob.glob(os.path.join(a.effects, "*.json"))):
        spec = json.load(open(f))
        spec.pop("camera", None)            # previewer only
        spec.pop("poster", None)
        spec.pop("dummies", None)
        t, m, md = used_assets(spec)
        all_tex |= t
        all_mesh |= m
        all_models |= md
        body = f"-- {spec['title']} ({spec['element']} {spec['archetype']}). Generated by scripts/effects.py + export_luau.py.\nreturn {lua(spec)}\n"
        open(os.path.join(eff_dir, spec["name"] + ".lua"), "w").write(body)
        index.append({"name": spec["name"], "title": spec["title"], "element": spec["element"], "archetype": spec["archetype"]})
    tex_lines = "".join(f'\t{n} = "rbxassetid://0", -- assets/textures/{n}.png\n' for n in sorted(all_tex))
    mesh_lines = "".join(f'\t{n} = "rbxassetid://0", -- assets/meshes/{n}.fbx\n' for n in sorted(all_mesh))
    open(os.path.join(a.out, "Assets.lua"), "w").write(ASSETS_TEMPLATE.format(textures=tex_lines, meshes=mesh_lines))
    manifest = {"textures": [f"assets/textures/{n}.png" for n in sorted(all_tex)], "meshes": [f"assets/meshes/{n}.fbx" for n in sorted(all_mesh)],
                "rig_models": [f"assets/meshes/{n}.fbx" for n in sorted(all_models)],  # import as skinned MeshParts into AnimeVFX.Models
                "effects": index}
    json.dump(manifest, open(os.path.join(HERE, "..", "assets", "upload_manifest.json"), "w"), indent=1)
    print(f"{len(index)} effects, {len(all_tex)} textures, {len(all_mesh)} meshes, {len(all_models)} rig models")


if __name__ == "__main__":
    main()
